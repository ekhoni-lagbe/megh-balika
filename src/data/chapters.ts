export const chapters: Chapter[] = novels.flatMap((novel) =>
  Array.from({ length: Math.min(novel.chapterCount, 5) }, (_, i) => ({
    id: `${novel.id}-ch${i + 1}`,
    novelId: novel.id,
    number: i + 1,
    title: [
      'প্রথম দেখা',
      'বৃষ্টির চিঠি',
      'অচেনা আলো',
      'পথের সন্ধানে',
      'নতুন শুরু',
    ][i] ?? `অধ্যায় ${i + 1}`,
    content: chapterTemplates[i % chapterTemplates.length],
    wordCount: 300 + i * 50,
  })),
);

export function getChaptersByNovel(novelId: string): Chapter[] {
  return chapters.filter((c) => c.novelId === novelId);
}

export function getChapter(novelId: string, chapterNumber: number): Chapter | undefined {
  return chapters.find((c) => c.novelId === novelId && c.number === chapterNumber);
}

// Generate placeholder chapter if beyond available data
export function getOrCreateChapter(novelId: string, chapterNumber: number): Chapter {
  const existing = getChapter(novelId, chapterNumber);
  if (existing) return existing;
  return {
    id: `${novelId}-ch${chapterNumber}`,
    novelId,
    number: chapterNumber,
    title: `অধ্যায় ${chapterNumber}`,
    content: chapterTemplates[0],
    wordCount: 300,
  };
}
